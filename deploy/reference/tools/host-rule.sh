#!/usr/bin/env bash
# host-rule.sh — print a [[waf.rules]] entry that refuses every Host but yours.
#
#   deploy/reference/tools/host-rule.sh app.example.com          # allows app.example.com[:443]
#   deploy/reference/tools/host-rule.sh app.example.com 8443     # allows app.example.com[:8443]
#
# Why this exists: eggrd 0.7 has no allowed-hosts setting (planned for 0.8 as `allowed_hosts`).
# Until then a WAF rule on the Host header does the job: `[waf] mode = "block"` plus
# `inspect_headers = true`, and a pattern that matches any Host line that is NOT the one you
# serve. The WAF's regex engine is linear-time and has no lookahead, so "not this host" has to be
# spelled out as its complement: every proper prefix of the name, every name that differs at some
# character, the name followed by something else, and the same for the port. This script writes
# that pattern so nobody has to by hand.
#
# What it gives you: a request whose Host is anything else (a raw IP, a forged name, empty) is
# answered 403 by the edge. What it does not: it is a WAF rule, so it only runs with the WAF in
# block mode and header inspection on, and it counts in edgeguard_waf_hits_total{rule="custom"}.
# One host per rule. Replace it with `allowed_hosts` once you run 0.8.
set -euo pipefail

host="${1:-}"
port="${2:-443}"
[ -n "$host" ] || { echo "usage: $0 <host> [port]" >&2; exit 2; }
case "$host" in *[!A-Za-z0-9.-]*) echo "host must be a plain DNS name: $host" >&2; exit 2 ;; esac
case "$port" in ''|*[!0-9]*) echo "port must be a number: $port" >&2; exit 2 ;; esac
host="${host,,}"

# Helpers set a variable rather than print, so the loops below fork nothing.
BS='\'
esc() { R="${1//./${BS}.}"; }                                  # dots escaped -> R
cls() { case "$1" in -) C="${BS}-" ;; *) C="$1" ;; esac; }     # one char inside [^...] -> C
TN="${BS}t${BS}n"                                               # the two characters \t\n
N="${BS}n"

alts=("")                                    # an empty Host
n=${#host}
for ((i = 1; i < n; i++)); do esc "${host:0:i}"; alts+=("$R"); done          # proper prefixes
cls "${host:0:1}"; alts+=("[^$C $TN].*")                                      # differs at char 1
for ((i = 1; i < n; i++)); do
  esc "${host:0:i}"; cls "${host:i:1}"; alts+=("$R[^$C$N].*")                 # differs at char i+1
done
esc "$host"; H="$R"
alts+=("$H[^:$N].*")                         # the name, then something other than a port
alts+=("$H:")
m=${#port}
for ((i = 1; i < m; i++)); do alts+=("$H:${port:0:i}"); done
alts+=("$H:[^${port:0:1}$N].*")
for ((i = 1; i < m; i++)); do alts+=("$H:${port:0:i}[^${port:i:1}$N].*"); done
alts+=("$H:$port.+")

joined="$(IFS='|'; printf '%s' "${alts[*]}")"
WS="[ ${BS}t]*"
printf '%s\n' \
  "# Refuse every Host but $host (or $host:$port). Generated by deploy/reference/tools/host-rule.sh." \
  "# Needs [waf] mode = \"block\" and inspect_headers = true. Replace with allowed_hosts on 0.8." \
  "[[waf.rules]]" \
  "id      = \"host-allowlist\"" \
  "target  = \"headers\"" \
  "pattern = '(?mi)^host:$WS(?:$joined)$WS\$'"
